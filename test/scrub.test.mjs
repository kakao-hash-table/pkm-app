// 내 정보 가리기 — 한 번에 훑어 바꾸고, 흔한 짧은 답은 두고, 이미 있는 자리표시는 겹쳐 바꾸지 않는다
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { scrub } from '../server/runner.js';

test('흔한 답(동의·예)은 글 곳곳의 같은 낱말을 바꾸지 않고, 이름·전화는 가린다', () => {
  assert.equal(scrub('마케팅 수신에 동의함 · 홍길동 010-1234-5678', { 마케팅동의: '동의', 이름: '홍길동', 전화: '010-1234-5678' }), '마케팅 수신에 동의함 · {{이름}} {{전화}}');
});
test('이미 있는 자리표시 안은 다시 바꾸지 않는다(예전: {{마케팅{{마케팅동의}}}})', () => {
  assert.equal(scrub('{{마케팅동의}} 마케팅', { 분야: '마케팅' }), '{{마케팅동의}} {{분야}}');
});
test('정규식 글자가 든 값도 그대로 찾고, 객체·배열 안까지 바꾼다', () => {
  assert.deepEqual(scrub({ a: ['a.b+c 김'] }, { y: 'a.b+c' }), { a: ['{{y}} 김'] });
  assert.equal(scrub('그대로', {}), '그대로');
});
